//! A description of the keys a view occupies.
//!
//! A view owns every key that starts with its base key, and the shape of what it puts there is
//! fixed by its type. [`DescribeLayout`] reports that shape, so that a raw key can be walked back
//! to the view that wrote it and the value under it can be decoded.
//!
//! The description is a grammar rather than a list of keys: a `MapView` holds one key per entry
//! and cannot enumerate them, but it can say that each is the base key followed by the
//! serialization of an index.

use serde::Serialize;

/// How a value is encoded.
#[derive(Debug, Serialize)]
pub enum ValueFormat {
    /// The BCS encoding of a value of the named type.
    Bcs {
        /// The name of the encoded type.
        type_name: &'static str,
    },
    /// A key whose presence is what matters; its value carries nothing.
    Marker,
    /// Bytes whose interpretation this description does not determine.
    Opaque {
        /// What the bytes are, for a human reader.
        description: &'static str,
    },
}

/// One arm of a [`ViewLayout::Tagged`].
#[derive(Debug, Serialize)]
pub struct TaggedArm {
    /// The tag byte appended to the base key.
    pub tag: u8,
    /// The name of the tag, as the view spells it.
    pub name: &'static str,
    /// What lives under it.
    pub layout: ViewLayout,
}

/// One field of a [`ViewLayout::Struct`].
#[derive(Debug, Serialize)]
pub struct StructField {
    /// The name of the field.
    pub name: &'static str,
    /// The index the derive macro assigned to it.
    pub index: u32,
    /// The type the index is encoded as in the key, which the macro widens once a struct has
    /// 256 fields or more.
    pub index_type: &'static str,
    /// The layout of the field's own view.
    pub layout: ViewLayout,
}

/// The shape of the keys a view occupies, relative to its base key.
#[derive(Debug, Serialize)]
pub enum ViewLayout {
    /// The view stores a single value at its base key, with nothing appended.
    Value(ValueFormat),
    /// The view appends a tag byte and continues underneath it.
    Tagged(Vec<TaggedArm>),
    /// The view appends the serialization of an index and continues underneath it.
    ///
    /// The index of a `ByteMapView` or a byte collection is the caller's raw bytes; for the
    /// typed wrappers it is the BCS encoding of the index type.
    Indexed {
        /// The type whose encoding forms the index, or `None` when the index is raw bytes.
        index: Option<&'static str>,
        /// What lives under each index.
        layout: Box<ViewLayout>,
    },
    /// The view is a struct whose fields each live under `[MIN_VIEW_TAG, field index]`.
    Struct(Vec<StructField>),
    /// Keys this description does not determine, because they are chosen by an application.
    Opaque {
        /// What the keys are, for a human reader.
        description: &'static str,
    },
}

impl ViewLayout {
    /// A convenience for the common case of a BCS-encoded value at the base key.
    pub fn value<T>() -> ViewLayout {
        ViewLayout::Value(ValueFormat::Bcs {
            type_name: short_type_name::<T>(),
        })
    }
}

/// A view that can describe the keys it occupies.
///
/// Implemented by hand for the views in this crate and generated by `#[derive(View)]` for
/// structs of views, so that the description and the key derivation cannot drift apart.
pub trait DescribeLayout {
    /// The shape of the keys this view occupies, relative to its base key.
    fn layout() -> ViewLayout;
}

/// The last segment of a type's path, which is the name `serde-reflection` registers a type
/// under.
///
/// `std::any::type_name` yields a fully qualified path, and generic parameters are dropped
/// because the registry names a type by its own identifier.
pub fn short_type_name<T>() -> &'static str {
    let name = std::any::type_name::<T>();
    let name = name.split('<').next().unwrap_or(name);
    name.rsplit("::").next().unwrap_or(name)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn short_type_name_drops_path_and_parameters() {
        assert_eq!(short_type_name::<u32>(), "u32");
        assert_eq!(short_type_name::<Vec<u8>>(), "Vec");
        assert_eq!(short_type_name::<ViewLayout>(), "ViewLayout");
        assert_eq!(short_type_name::<Option<Box<ViewLayout>>>(), "Option");
    }
}
